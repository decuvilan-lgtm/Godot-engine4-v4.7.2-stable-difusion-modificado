#!/usr/bin/env python3
"""Inject the one-way GitHub sync EditorPlugin into ZIP-installed projects."""
from pathlib import Path
import sys

REPO_ROOT = Path(__file__).resolve().parents[1]
ROOT = REPO_ROOT / "godot-source"
SOURCE = ROOT / "editor/project_manager/project_dialog.cpp"
MANAGER_SOURCE = ROOT / "editor/project_manager/project_manager.cpp"
ADDON = REPO_ROOT / "scripts/github_sync_addon"
TERRAIN_ADDON = REPO_ROOT / "scripts/terrain_3d_addon"

def replace_once(content: str, old: str, new: str, label: str) -> str:
    count = content.count(old)
    if count != 1:
        raise RuntimeError(f"{label}: expected one anchor, found {count}: {old[:100]!r}")
    return content.replace(old, new, 1)

if not SOURCE.is_file():
    sys.exit("Godot source tree not found; run this after apply_github_import_patch.py.")
plugin_path = ADDON / "plugin.gd"
config_path = ADDON / "plugin.cfg"
terrain_plugin_path = TERRAIN_ADDON / "terrain_editor_plugin.gd"
terrain_data_path = TERRAIN_ADDON / "terrain_data.gd"
terrain_config_path = TERRAIN_ADDON / "plugin.cfg"
if not all(p.is_file() for p in (plugin_path, config_path, terrain_plugin_path, terrain_data_path, terrain_config_path)):
    sys.exit("GitHub sync or terrain addon files are missing.")

plugin = plugin_path.read_text(encoding="utf-8")
config = config_path.read_text(encoding="utf-8")
terrain_plugin = terrain_plugin_path.read_text(encoding="utf-8")
terrain_data = terrain_data_path.read_text(encoding="utf-8")
terrain_config = terrain_config_path.read_text(encoding="utf-8")
# Delimiter is intentionally long and checked so addon source cannot terminate the C++ raw string.
delimiter = "GHGODOTSYNC"
for value in (plugin, config, terrain_plugin, terrain_data, terrain_config):
    if f"){delimiter}\"" in value:
        raise RuntimeError("Addon content collides with the generated C++ raw-string delimiter.")

generated_header = ROOT / "editor/github_sync_addon_data.h"
generated_header.write_text(
    "#pragma once\n"
    "// Generated by scripts/apply_github_sync_patch.py; do not edit in godot-source.\n"
    "namespace GitHubSyncAddonData {\n"
    f'static const char *PLUGIN_GD = R"{delimiter}({plugin}){delimiter}";\n'
    f'static const char *PLUGIN_CFG = R"{delimiter}({config}){delimiter}";\n'
    f'static const char *TERRAIN_PLUGIN_GD = R"{delimiter}({terrain_plugin}){delimiter}";\n'
    f'static const char *TERRAIN_DATA_GD = R"{delimiter}({terrain_data}){delimiter}";\n'
    f'static const char *TERRAIN_PLUGIN_CFG = R"{delimiter}({terrain_config}){delimiter}";\n'
    "}\n",
    encoding="utf-8",
)

source = SOURCE.read_text(encoding="utf-8")
source = replace_once(
    source,
    '#include "project_dialog.h"\n',
    '#include "project_dialog.h"\n#include "editor/github_sync_addon_data.h"\n',
    "include generated GitHub sync addon",
)
anchor = """\t\terr = cfg.save(project_godot);
\t\tif (err != OK) {
\t\t\tdialog_error->set_text(vformat(TTR("Couldn't save project at '%s' (error %d)."), project_godot, err));
\t\t\tdialog_error->popup_centered();
\t\t\treturn;
\t\t}
\t}

\thide();"""
insertion = """\t\terr = cfg.save(project_godot);
\t\tif (err != OK) {
\t\t\tdialog_error->set_text(vformat(TTR("Couldn't save project at '%s' (error %d)."), project_godot, err));
\t\t\tdialog_error->popup_centered();
\t\t\treturn;
\t\t}

\t\t// Install the one-way GitHub sync editor plugin in ZIP-installed projects.
\t\t// It only reads public GitHub content and never pushes local files.
\t\tif (mode == MODE_INSTALL) {
\t\t\tconst String addon_dir_path = path.path_join("addons/github_sync");
\t\t\tRef<DirAccess> addon_dir = DirAccess::create(DirAccess::ACCESS_FILESYSTEM);
\t\t\tError addon_err = addon_dir->make_dir_recursive(addon_dir_path);
\t\t\tif (addon_err != OK) {
\t\t\t\tdialog_error->set_text(vformat(TTR("Couldn't create GitHub sync addon directory (error %d)."), addon_err));
\t\t\t\tdialog_error->popup_centered();
\t\t\t\treturn;
\t\t\t}
\t\t\tauto write_sync_addon_file = [](const String &p_file_path, const String &p_contents) -> Error {
\t\t\t\tRef<FileAccess> file = FileAccess::open(p_file_path, FileAccess::WRITE);
\t\t\t\tif (file.is_null()) {
\t\t\t\t\treturn FileAccess::get_open_error();
\t\t\t\t}
\t\t\t\tfile->store_string(p_contents);
\t\t\t\treturn file->get_error();
\t\t\t};
\t\t\taddon_err = write_sync_addon_file(addon_dir_path.path_join("plugin.gd"), String::utf8(GitHubSyncAddonData::PLUGIN_GD));
\t\t\tif (addon_err == OK) {
\t\t\t\taddon_err = write_sync_addon_file(addon_dir_path.path_join("plugin.cfg"), String::utf8(GitHubSyncAddonData::PLUGIN_CFG));
\t\t\tconst String terrain_addon_dir_path = path.path_join("addons/terrain_3d");
\t\t\tif (addon_err == OK) {
\t\t\t\tRef<DirAccess> terrain_addon_dir = DirAccess::create(DirAccess::ACCESS_FILESYSTEM);
\t\t\t\taddon_err = terrain_addon_dir->make_dir_recursive(terrain_addon_dir_path);
\t\t\t}
\t\t\tif (addon_err == OK) {
\t\t\t\taddon_err = write_sync_addon_file(terrain_addon_dir_path.path_join("terrain_editor_plugin.gd"), String::utf8(GitHubSyncAddonData::TERRAIN_PLUGIN_GD));
\t\t\t}
\t\t\tif (addon_err == OK) {
\t\t\t\taddon_err = write_sync_addon_file(terrain_addon_dir_path.path_join("terrain_data.gd"), String::utf8(GitHubSyncAddonData::TERRAIN_DATA_GD));
\t\t\t}
\t\t\tif (addon_err == OK) {
\t\t\t\taddon_err = write_sync_addon_file(terrain_addon_dir_path.path_join("plugin.cfg"), String::utf8(GitHubSyncAddonData::TERRAIN_PLUGIN_CFG));
\t\t\t}
\t\t\t}
\t\t\tif (addon_err != OK) {
\t\t\t\tdialog_error->set_text(vformat(TTR("Couldn't install GitHub sync addon (error %d)."), addon_err));
\t\t\t\tdialog_error->popup_centered();
\t\t\t\treturn;
\t\t\t}
\t\t\tPackedStringArray enabled_plugins = cfg.get_value("editor_plugins", "enabled", PackedStringArray());
\t\t\tconst String plugin_setting = "res://addons/github_sync/plugin.cfg";
\t\t\tconst String terrain_plugin_setting = "res://addons/terrain_3d/plugin.cfg";
\t\t\tbool plugins_changed = false;
\t\t\tif (!enabled_plugins.has(plugin_setting)) {
\t\t\t\tenabled_plugins.push_back(plugin_setting);
\t\t\t\tplugins_changed = true;
\t\t\t}
\t\t\tif (!enabled_plugins.has(terrain_plugin_setting)) {
\t\t\t\tenabled_plugins.push_back(terrain_plugin_setting);
\t\t\t\tplugins_changed = true;
\t\t\t}
\t\t\tif (plugins_changed) {
\t\t\t\tcfg.set_value("editor_plugins", "enabled", enabled_plugins);
\t\t\t\taddon_err = cfg.save(project_godot);
\t\t\t\tif (addon_err != OK) {
\t\t\t\t\tdialog_error->set_text(vformat(TTR("Editor addons were copied, but could not be enabled (error %d)."), addon_err));
\t\t\t\t\tdialog_error->popup_centered();
\t\t\t\t\treturn;
\t\t\t\t}
\t\t\t}
\t\t}
\t}

\thide();"""
source = replace_once(source, anchor, insertion, "install and enable sync addon after ZIP extraction")
SOURCE.write_text(source, encoding="utf-8")
print("PASS: generated embedded sync addon header")
print("PASS: ZIP-installed projects receive and enable the GitHub sync editor plugin")
print("Note: this is source validation only; C++/GDScript runtime and Android behavior remain unverified.")

manager_source = MANAGER_SOURCE.read_text(encoding="utf-8")
manager_source = replace_once(
    manager_source,
    '#include "project_manager.h"\n',
    '#include "project_manager.h"\n#include "editor/github_sync_addon_data.h"\n',
    "include embedded addons in Project Manager",
)
manager_anchor = '\t\tprint_line("Editing project: " + path);'
manager_insertion = """\t\t// Make the in-editor tools available to existing projects too, before the editor process starts.
\t\t// Existing addon files are left untouched; this only fills missing files and enables the plugins.
\t\tconst String sync_addon_dir = path.path_join("addons/github_sync");
\t\tconst String terrain_addon_dir = path.path_join("addons/terrain_3d");
\t\tRef<DirAccess> addon_directory = DirAccess::create(DirAccess::ACCESS_FILESYSTEM);
\t\tError addon_install_error = addon_directory->make_dir_recursive(sync_addon_dir);
\t\tif (addon_install_error == OK) {
\t\t\taddon_install_error = addon_directory->make_dir_recursive(terrain_addon_dir);
\t\t}
\t\tauto write_addon_if_missing = [](const String &p_path, const String &p_content) -> Error {
\t\t\tif (FileAccess::exists(p_path)) {
\t\t\t\treturn OK;
\t\t\t}
\t\t\tRef<FileAccess> file = FileAccess::open(p_path, FileAccess::WRITE);
\t\t\tif (file.is_null()) {
\t\t\t\treturn FileAccess::get_open_error();
\t\t\t}
\t\t\tfile->store_string(p_content);
\t\t\treturn file->get_error();
\t\t};
\t\tif (addon_install_error == OK) {
\t\t\taddon_install_error = write_addon_if_missing(sync_addon_dir.path_join("plugin.gd"), String::utf8(GitHubSyncAddonData::PLUGIN_GD));
\t\t}
\t\tif (addon_install_error == OK) {
\t\t\taddon_install_error = write_addon_if_missing(sync_addon_dir.path_join("plugin.cfg"), String::utf8(GitHubSyncAddonData::PLUGIN_CFG));
\t\t}
\t\tif (addon_install_error == OK) {
\t\t\taddon_install_error = write_addon_if_missing(terrain_addon_dir.path_join("terrain_editor_plugin.gd"), String::utf8(GitHubSyncAddonData::TERRAIN_PLUGIN_GD));
\t\t}
\t\tif (addon_install_error == OK) {
\t\t\taddon_install_error = write_addon_if_missing(terrain_addon_dir.path_join("terrain_data.gd"), String::utf8(GitHubSyncAddonData::TERRAIN_DATA_GD));
\t\t}
\t\tif (addon_install_error == OK) {
\t\t\taddon_install_error = write_addon_if_missing(terrain_addon_dir.path_join("plugin.cfg"), String::utf8(GitHubSyncAddonData::TERRAIN_PLUGIN_CFG));
\t\t}
\t\tif (addon_install_error == OK) {
\t\t\tConfigFile project_cfg;
\t\t\taddon_install_error = project_cfg.load(conf);
\t\t\tif (addon_install_error == OK) {
\t\t\t\tPackedStringArray enabled_plugins = project_cfg.get_value("editor_plugins", "enabled", PackedStringArray());
\t\t\t\tbool plugins_changed = false;
\t\t\t\tconst String sync_plugin = "res://addons/github_sync/plugin.cfg";
\t\t\t\tconst String terrain_plugin = "res://addons/terrain_3d/plugin.cfg";
\t\t\t\tif (!enabled_plugins.has(sync_plugin)) {
\t\t\t\t\tenabled_plugins.push_back(sync_plugin);
\t\t\t\t\tplugins_changed = true;
\t\t\t\t}
\t\t\t\tif (!enabled_plugins.has(terrain_plugin)) {
\t\t\t\t\tenabled_plugins.push_back(terrain_plugin);
\t\t\t\t\tplugins_changed = true;
\t\t\t\t}
\t\t\t\tif (plugins_changed) {
\t\t\t\t\tproject_cfg.set_value("editor_plugins", "enabled", enabled_plugins);
\t\t\t\t\taddon_install_error = project_cfg.save(conf);
\t\t\t\t}
\t\t\t}
\t\t}
\t\tif (addon_install_error != OK) {
\t\t\tERR_PRINT(vformat("Could not install the custom editor addons in project '%s' (error %d). The project will still open.", path, addon_install_error));
\t\t}
"""
manager_source = replace_once(
    manager_source,
    manager_anchor,
    manager_insertion + manager_anchor,
    "install custom addons before launching any existing project",
)
MANAGER_SOURCE.write_text(manager_source, encoding="utf-8")
print("PASS: existing projects receive missing custom addons before the editor process launches")
